#!/usr/bin/env node
// Checks that every language has exactly the same keys and placeholders as en.json,
// then generates the GetX translations map for Flutter.
//   node shared/i18n/build.mjs [--check]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url)); const root = resolve(here, '../..');
const LANGS = ['en', 'hi', 'gu', 'es', 'fr'];
const data = Object.fromEntries(LANGS.map((l) => [l, JSON.parse(readFileSync(join(here, `${l}.json`), 'utf8'))]));
const ph = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
const errors = [];
for (const l of LANGS.slice(1)) {
  for (const k of Object.keys(data.en)) { if (!(k in data[l])) errors.push(`${l}: missing ${k}`); else if (ph(data[l][k]) !== ph(data.en[k])) errors.push(`${l}: placeholder mismatch in ${k}`); else if (!data[l][k].trim()) errors.push(`${l}: empty ${k}`); }
  for (const k of Object.keys(data[l])) if (!(k in data.en)) errors.push(`${l}: extra key ${k}`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\{(\w+)\}/g, '@$1');
// 'auth.send_code' -> authSendCode
const camel = (k) => k.split(/[._]/).filter(Boolean).map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w)).join('');
const locale = { en: 'en_IN', hi: 'hi_IN', gu: 'gu_IN', es: 'es_ES', fr: 'fr_FR' };
const head = '// GENERATED by shared/i18n/build.mjs from shared/i18n/*.json — do not edit.';

const keys = [head, '// Use as LangKeys.authSendCode.tr; values with {name} use .trParams({\'name\': …}).', '', 'abstract final class LangKeys {'];
const seen = new Map();
for (const [k, v] of Object.entries(data.en)) {
  const name = camel(k);
  if (seen.has(name)) { console.error(`keys ${seen.get(name)} and ${k} both become LangKeys.${name}`); process.exit(1); }
  seen.set(name, k);
  keys.push(`  /// ${v.replace(/\n/g, ' ')}`, `  static const ${name} = '${k}';`);
}
keys.push('}', '');

const maps = [head, '// Placeholders use GetX @name syntax (trParams).', "import 'package:get/get.dart';", '', 'class KnTranslations extends Translations {', '  @override', '  Map<String, Map<String, String>> get keys => {'];
for (const l of LANGS) { maps.push(`        '${locale[l]}': {`); for (const [k, v] of Object.entries(data[l])) maps.push(`          '${k}': '${esc(v)}',`); maps.push('        },'); }
maps.push('      };', '}', '');

const outputs = {
  'mobile/lib/infrastructure/lang/lang_keys.g.dart': keys.join('\n'),
  'mobile/lib/infrastructure/lang/translations.g.dart': maps.join('\n'),
};
const stale = [];
for (const [rel, body] of Object.entries(outputs)) {
  const p = join(root, rel);
  if (process.argv.includes('--check')) { if (!existsSync(p) || readFileSync(p, 'utf8') !== body) stale.push(rel); continue; }
  mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, body); console.log('wrote', rel);
}
if (stale.length) { console.error('Stale translations, run: node shared/i18n/build.mjs\n  ' + stale.join('\n  ')); process.exit(1); }
if (process.argv.includes('--check')) console.log(`i18n OK: ${Object.keys(data.en).length} keys × ${LANGS.length} languages`);
